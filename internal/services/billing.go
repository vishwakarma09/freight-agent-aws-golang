package services

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"html"
	"log"
	"strings"
	"time"

	"github.com/vishwakarma09/freight-agent-aws-golang/internal/models"
)

type InvoiceDocumentResult struct {
	InvoiceID string `json:"invoice_id"`
	S3Key     string `json:"s3_key"`
	Status    string `json:"status"`
}

type BOLDocumentResult struct {
	BOLID  string `json:"bol_id"`
	S3Key  string `json:"s3_key"`
	Status string `json:"status"`
}

// GenerateInvoiceDocument creates an HTML commercial freight invoice and uploads it to the org-scoped private S3 bucket.
func GenerateInvoiceDocument(quote *models.FreightQuote, customerName string) InvoiceDocumentResult {
	b := make([]byte, 4)
	_, _ = rand.Read(b)
	invoiceID := fmt.Sprintf("INV-%s", strings.ToUpper(hex.EncodeToString(b)))
	s3Key := fmt.Sprintf("orgs/%d/quotes/%s/%s.html", quote.OrganizationID, quote.ID, invoiceID)

	docHTML := fmt.Sprintf(`<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8"><title>Freight Invoice %s</title>
<style>body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;max-width:760px;margin:40px auto;color:#0f172a;padding:24px;}
.hdr{display:flex;justify-content:space-between;border-bottom:2px solid #0f172a;padding-bottom:16px;margin-bottom:24px;}
table{width:100%%;border-collapse:collapse;margin-top:20px;}th,td{border:1px solid #cbd5e1;padding:10px;text-align:left;}
th{background:#f8fafc;}.total{font-size:20px;font-weight:700;text-align:right;margin-top:24px;}</style>
</head>
<body>
<div class="hdr">
  <div><h1>DISPATCH FREIGHT INVOICE</h1><p>Invoice #: <b>%s</b> | Quote Ref: <b>%s</b></p></div>
  <div><p>Issued: %s</p><p>Status: PENDING PAYMENT</p></div>
</div>
<p><b>Bill To:</b> %s</p>
<table>
  <thead><tr><th>Lane</th><th>Weight</th><th>Freight Class</th><th>Pickup Date</th><th>Amount Due</th></tr></thead>
  <tbody>
    <tr>
      <td>%s &rarr; %s</td>
      <td>%.2f lbs</td>
      <td>%s</td>
      <td>%s</td>
      <td><b>$%.2f USD</b></td>
    </tr>
  </tbody>
</table>
<div class="total">Total Due: $%.2f USD</div>
<p style="margin-top:32px;font-size:12px;color:#64748b;">Generated by Dispatch Freight Execution Engine. Store for brokerage audit and reconciliation.</p>
</body></html>`,
		html.EscapeString(invoiceID),
		html.EscapeString(invoiceID),
		html.EscapeString(quote.ID),
		time.Now().UTC().Format("2006-01-02"),
		html.EscapeString(customerName),
		html.EscapeString(quote.Origin),
		html.EscapeString(quote.Destination),
		quote.WeightLbs,
		html.EscapeString(getSafeString(quote.FreightClass)),
		quote.PickupDate.Format("2006-01-02"),
		quote.SellPrice,
		quote.SellPrice,
	)

	if err := UploadDocumentBytes(s3Key, "text/html; charset=utf-8", []byte(docHTML)); err != nil {
		log.Printf("Warning: could not upload invoice %s to S3 (%s): %v\n", invoiceID, s3Key, err)
	} else {
		log.Printf("Uploaded private freight invoice %s to s3://%s\n", invoiceID, s3Key)
	}

	return InvoiceDocumentResult{
		InvoiceID: invoiceID,
		S3Key:     s3Key,
		Status:    "ISSUED",
	}
}

// GenerateBOLDocument creates an HTML Straight Bill of Lading and uploads it to the org-scoped private S3 bucket.
func GenerateBOLDocument(quote *models.FreightQuote, carrierName string, customerName string) BOLDocumentResult {
	b := make([]byte, 4)
	_, _ = rand.Read(b)
	bolID := fmt.Sprintf("BOL-%s", strings.ToUpper(hex.EncodeToString(b)))
	s3Key := fmt.Sprintf("orgs/%d/quotes/%s/%s.html", quote.OrganizationID, quote.ID, bolID)

	hazmatLabel := "NO"
	if quote.Hazmat {
		hazmatLabel = "YES - HAZARDOUS MATERIALS"
	}

	docHTML := fmt.Sprintf(`<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8"><title>Bill of Lading %s</title>
<style>body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;max-width:760px;margin:40px auto;color:#0f172a;padding:24px;}
.hdr{display:flex;justify-content:space-between;border-bottom:2px solid #0f172a;padding-bottom:16px;margin-bottom:24px;}
table{width:100%%;border-collapse:collapse;margin-top:20px;}th,td{border:1px solid #cbd5e1;padding:10px;text-align:left;}
th{background:#f8fafc;}</style>
</head>
<body>
<div class="hdr">
  <div><h1>STRAIGHT BILL OF LADING</h1><p>BOL #: <b>%s</b> | Quote Ref: <b>%s</b></p></div>
  <div><p>Date: %s</p><p>Carrier: <b>%s</b></p></div>
</div>
<table>
  <tr><th>Shipper / Customer</th><td>%s</td></tr>
  <tr><th>Origin</th><td>%s</td></tr>
  <tr><th>Destination</th><td>%s</td></tr>
  <tr><th>Pickup Date</th><td>%s</td></tr>
  <tr><th>Weight / Dimensions</th><td>%.2f lbs (%s)</td></tr>
  <tr><th>Freight Class</th><td>%s</td></tr>
  <tr><th>Hazmat</th><td>%s</td></tr>
  <tr><th>Accessorials</th><td>%s</td></tr>
</table>
<p style="margin-top:40px;">Shipper Signature: _______________________ &nbsp;&nbsp; Carrier Signature: _______________________</p>
</body></html>`,
		html.EscapeString(bolID),
		html.EscapeString(bolID),
		html.EscapeString(quote.ID),
		time.Now().UTC().Format("2006-01-02"),
		html.EscapeString(carrierName),
		html.EscapeString(customerName),
		html.EscapeString(quote.Origin),
		html.EscapeString(quote.Destination),
		quote.PickupDate.Format("2006-01-02"),
		quote.WeightLbs,
		html.EscapeString(getSafeString(quote.Dimensions)),
		html.EscapeString(getSafeString(quote.FreightClass)),
		hazmatLabel,
		html.EscapeString(getSafeString(quote.Accessorials)),
	)

	if err := UploadDocumentBytes(s3Key, "text/html; charset=utf-8", []byte(docHTML)); err != nil {
		log.Printf("Warning: could not upload BOL %s to S3 (%s): %v\n", bolID, s3Key, err)
	} else {
		log.Printf("Uploaded private BOL %s to s3://%s\n", bolID, s3Key)
	}

	return BOLDocumentResult{
		BOLID:  bolID,
		S3Key:  s3Key,
		Status: "ISSUED",
	}
}
